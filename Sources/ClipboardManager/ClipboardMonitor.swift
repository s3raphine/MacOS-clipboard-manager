import Foundation
import AppKit
import Combine

final class ClipboardMonitor: ObservableObject {
    @Published var items: [ClipboardItem] = []
    @Published var searchQuery: String = "" {
        didSet { selectedID = nil }
    }
    @Published var selectedID: UUID?

    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var lastChangeCount: Int
    private let maxUnpinnedItems = 100
    private let maxUnpinnedImages = 30
    private let saveURL: URL
    private let saveQueue = DispatchQueue(label: "ClipboardManager.save", qos: .utility)

    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType")
    ]

    var filteredItems: [ClipboardItem] {
        let query = searchQuery.trimmingCharacters(in: .whitespacesAndNewlines)
        let base = query.isEmpty ? items : items.filter { $0.text.localizedCaseInsensitiveContains(query) }
        return base.sorted { lhs, rhs in
            if lhs.isPinned != rhs.isPinned {
                return lhs.isPinned
            }
            return lhs.timestamp > rhs.timestamp
        }
    }

    var selectedItem: ClipboardItem? {
        let visible = filteredItems
        return visible.first { $0.id == selectedID } ?? visible.first
    }

    init(pasteboard: NSPasteboard = .general, directory: URL? = nil) {
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount

        let appSupport = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
        let dir = directory ?? appSupport.appendingPathComponent("ClipboardManager", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        self.saveURL = dir.appendingPathComponent("history.json")

        loadHistory()
    }

    func startMonitoring() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.checkPasteboard()
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stopMonitoring() {
        timer?.invalidate()
        timer = nil
    }

    func checkPasteboard() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            addItem(text: urls.map(\.path).joined(separator: "\n"), type: .file)
            return
        }

        let hasImage = types.contains(.png) || types.contains(.tiff)
        let string = pasteboard.string(forType: .string)
        let hasText = !(string ?? "").trimmingCharacters(in: .whitespacesAndNewlines).isEmpty

        if let string, hasText {
            let type = ClipboardItem.detectType(from: string)
            if !(hasImage && type == .url) {
                addItem(text: string, type: type)
                return
            }
        }

        if hasImage, let image = readImage() {
            addItem(text: "Image (\(image.width)×\(image.height))", type: .image, imageData: image.png)
        }
    }

    private func readImage() -> (png: Data, width: Int, height: Int)? {
        let png = pasteboard.data(forType: .png)
        guard let data = png ?? pasteboard.data(forType: .tiff),
              let bitmap = NSBitmapImageRep(data: data),
              let pngData = png ?? bitmap.representation(using: .png, properties: [:]) else { return nil }
        return (pngData, bitmap.pixelsWide, bitmap.pixelsHigh)
    }

    private func addItem(text: String, type: ClipboardContentType, imageData: Data? = nil) {
        if let index = items.firstIndex(where: { $0.text == text && $0.imageData == imageData }) {
            var existing = items.remove(at: index)
            existing.timestamp = Date()
            items.insert(existing, at: 0)
        } else {
            items.insert(ClipboardItem(text: text, type: type, imageData: imageData), at: 0)
        }
        trimHistory()
        saveHistory()
    }

    private func trimHistory() {
        var toRemove = Set<UUID>()
        let unpinned = items.filter { !$0.isPinned }
        toRemove.formUnion(unpinned.dropFirst(maxUnpinnedItems).map(\.id))
        toRemove.formUnion(unpinned.filter { $0.type == .image }.dropFirst(maxUnpinnedImages).map(\.id))
        if !toRemove.isEmpty {
            items.removeAll { toRemove.contains($0.id) }
        }
    }

    func copyToClipboard(_ item: ClipboardItem) {
        pasteboard.clearContents()

        switch item.type {
        case .image:
            if let image = item.nsImage { pasteboard.writeObjects([image]) }
        case .file:
            pasteboard.writeObjects(item.fileURLs as [NSURL])
        case .text, .url, .color:
            pasteboard.setString(item.text, forType: .string)
        }
        lastChangeCount = pasteboard.changeCount

        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var used = items.remove(at: index)
            used.timestamp = Date()
            items.insert(used, at: 0)
            saveHistory()
        }
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        saveHistory()
    }

    func delete(_ item: ClipboardItem) {
        let visible = filteredItems
        if let index = visible.firstIndex(where: { $0.id == item.id }) {
            let remaining = visible.filter { $0.id != item.id }
            selectedID = remaining.isEmpty ? nil : remaining[min(index, remaining.count - 1)].id
        }
        items.removeAll { $0.id == item.id }
        saveHistory()
    }

    func clearHistory(keepPinned: Bool = true) {
        if keepPinned {
            items.removeAll { !$0.isPinned }
        } else {
            items.removeAll()
        }
        selectedID = nil
        saveHistory()
    }

    func moveSelection(by offset: Int) {
        let visible = filteredItems
        guard !visible.isEmpty else { return }
        let current = visible.firstIndex { $0.id == selectedItem?.id } ?? 0
        selectedID = visible[max(0, min(visible.count - 1, current + offset))].id
    }

    func resetForOpening() {
        searchQuery = ""
        selectedID = nil
    }

    private func saveHistory() {
        let toSave = items.filter { $0.type != .image || $0.isPinned }
        let url = saveURL
        saveQueue.async {
            guard let data = try? JSONEncoder().encode(toSave) else { return }
            try? data.write(to: url, options: [.atomic])
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        }
    }

    func flushPendingSaves() {
        saveQueue.sync {}
    }

    private func loadHistory() {
        guard let data = try? Data(contentsOf: saveURL) else { return }
        guard let decoded = try? JSONDecoder().decode([ClipboardItem].self, from: data) else {
            let backup = saveURL.deletingLastPathComponent().appendingPathComponent("history.corrupt.json")
            try? FileManager.default.removeItem(at: backup)
            try? FileManager.default.moveItem(at: saveURL, to: backup)
            return
        }
        items = decoded
    }
}
